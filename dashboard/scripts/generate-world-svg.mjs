#!/usr/bin/env node
/**
 * Ticket #18: precompute an SVG path set from the committed world geometry
 * (public/geo/world.json, Natural Earth 110m) so the source-market map renders
 * as pure SVG at render time.
 *
 * CHOICE (documented per the ticket): precomputed paths over d3-geo. The
 * projection below (equirectangular, latitude clamped to 84°N..58°S to drop
 * Antarctica) is a few lines of plain arithmetic, so the dashboard keeps ZERO
 * new runtime dependencies and stays fully offline. The script runs at build
 * time (wired into prebuild) with only node:fs/node:path — no network.
 *
 * Output: src/lib/world-paths.generated.ts — a committed, deterministic TS
 * module ({ name, d } per feature) the map component imports directly.
 * Geometry is not a displayed figure, so committing the generated file does
 * not touch the "every number computed at render time" rule; the script is
 * deterministic and re-runs on every build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dashboardRoot = join(here, "..");
const source = join(dashboardRoot, "public", "geo", "world.json");
const output = join(dashboardRoot, "src", "lib", "world-paths.generated.ts");

const WIDTH = 960;
const LAT_MAX = 84; // drop the high Arctic ocean filler
const LAT_MIN = -58; // drop Antarctica — no source market there
const HEIGHT = Math.round((WIDTH * (LAT_MAX - LAT_MIN)) / 360);

function project([lon, lat]) {
  return [
    Math.round(((lon + 180) / 360) * WIDTH * 10) / 10,
    Math.round(((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * HEIGHT * 10) / 10,
  ];
}

function ringToPath(ring) {
  if (!Array.isArray(ring) || ring.length < 3) return "";
  const parts = ring.map((pt, i) => {
    const [x, y] = project(pt);
    return `${i === 0 ? "M" : "L"}${x} ${y}`;
  });
  parts.push("Z");
  return parts.join("");
}

function geometryToPaths(geometry) {
  let polys = [];
  if (geometry.type === "Polygon") polys = [geometry.coordinates];
  else if (geometry.type === "MultiPolygon") polys = geometry.coordinates;
  // One path per feature; holes render via fill-rule="evenodd".
  const d = polys.map((rings) => rings.map(ringToPath).join("")).join("");
  return d;
}

const world = JSON.parse(readFileSync(source, "utf8"));
const features = [];
for (const f of world.features) {
  const name = f.properties?.name;
  if (!name) continue;
  const d = geometryToPaths(f.geometry);
  if (!d) continue;
  features.push({ name, d });
}

const body = `/**
 * GENERATED by scripts/generate-world-svg.mjs from public/geo/world.json —
 * do not edit by hand. Equirectangular projection, latitude clamped to
 * ${LAT_MAX}N..${Math.abs(LAT_MIN)}S. Coordinates are rounded to 0.1px.
 */
export interface WorldPath {
  name: string;
  d: string;
}

export const WORLD_MAP_WIDTH = ${WIDTH};
export const WORLD_MAP_HEIGHT = ${HEIGHT};

export const WORLD_PATHS: WorldPath[] = ${JSON.stringify(features)};
`;

writeFileSync(output, body);
console.log(`[generate-world-svg] wrote ${features.length} features -> ${output} (${HEIGHT}px tall)`);
